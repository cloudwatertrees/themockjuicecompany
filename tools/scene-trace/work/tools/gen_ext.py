"""Write ForestPathExtension.swift: the live file's wrapper code with its header, layer switch, seam and bounce
colours and data blocks replaced. B's data is in its own design space: y = 0 on its top edge, which is the live
art's bottom edge.
usage: gen_ext.py LIVE_EXT.swift DATADIR A.png B.png OUT.swift"""
import os, re, sys
import numpy as np
from PIL import Image

LAYERS = ['meadow', 'pathEdges', 'path', 'water', 'rocks', 'wood', 'foliage', 'conifers', 'accents', 'flowers']

src, datadir, a_png, b_png, out = sys.argv[1:6]
text = open(src).read()
code = text[:text.index('// MARK: - Layer data')]
A = np.asarray(Image.open(a_png).convert('RGB')).astype(float)
B = np.asarray(Image.open(b_png).convert('RGB')).astype(float)


def rgb(c):
    r, g, b = (int(round(v)) for v in c)
    return f'RGB(r: {r}, g: {g}, b: {b})'


code = re.sub(r'\A.*?(?=/// Downward continuation)', '''import SwiftUI

// Generated by tools/scene-trace/work/tools/gen_ext.py from tools/scene-trace/B_seam.png (traced with
// tools/scene-trace/i2s/pipeline.py). Do not edit by hand; change the source or the generator and regenerate.

''', code, count=1, flags=re.S)
code = re.sub(r'static let seamGround = RGB\(.*?\)', 'static let seamGround = ' + rgb(B[:200].reshape(-1, 3).mean(0)), code)
code = re.sub(r'static let topBounce = RGB\(.*?\)', 'static let topBounce = ' + rgb(A[:24].reshape(-1, 3).mean(0)), code)
code = re.sub(r'static let bottomBounce = RGB\(.*?\)', 'static let bottomBounce = ' + rgb(B[-24:].reshape(-1, 3).mean(0)), code)
switch = '\n'.join(f'        case .{n}: return {n}' for n in LAYERS)
code = re.sub(r'(static func data\(of id: LayerID\) -> String \{\n\s*switch id \{\n)(.*?)(\n\s*\}\n\s*\})',
              lambda m: m.group(1) + switch + m.group(3), code, count=1, flags=re.S)
blocks = []
for n in LAYERS:
    p = os.path.join(datadir, n + '.txt')
    lines = [l for l in open(p).read().split('\n') if l.strip()] if os.path.exists(p) else []
    body = '\n'.join('        ' + l for l in lines)
    blocks.append(f'    static let {n}: String = """\n' + (body + '\n' if body else '') + '        """')
text = (code + '// MARK: - Layer data\n//\n// Back to front within each layer; format as in `ForestPathArt.data(of:)`.\n\n'
        'nonisolated extension ForestPathExtensionArt {\n' + '\n'.join(blocks) + '\n}\n')
open(out, 'w').write(text)
print('wrote', out, os.path.getsize(out), 'bytes')
