"""Write ios/mockjuice/Views/Components/ForestPathExtension.swift from the extension scene.

python emit_swift.py [rebuild]   (rebuild: regenerate the scene instead of using the cached data)
The file holds: the art API (parse with ShapeDataReader, rasterise with ShapeRaster, same fill transform as the live
art), colours for the loading fallback and the scroll bounces, and the layer data in the live format."""
import sys
import numpy as np
from common import *
from art import rgb2hex
from extdata import load_ext_layers

require_facts()
ext = load_ext_layers(rebuild='rebuild' in sys.argv)
by = {L: [s.line() for s in ext if s.layer == L] for L in LAYERS}

# colours: live top row (top bounce), extension bottom row (bottom bounce), extension mean (loading fallback)
live_top = render(in_box(load_live_layers(), (0, 0, W, 6), 2), 1.0, (0, 0, W, 6))[:3].reshape(-1, 3).mean(0)
ext_img = render(ext, 0.25, (0, 0, W, H))
ext_bottom = ext_img[-3:].reshape(-1, 3).mean(0)
ext_mean = ext_img[:int(ext_img.shape[0] * 0.12)].reshape(-1, 3).mean(0)     # ground near the seam


def rgb(c):
    c = np.clip(np.round(np.asarray(c) * 255), 0, 255).astype(int)
    return 'RGB(r: %d, g: %d, b: %d)' % tuple(c)


facts = require_facts()
cases = '\n'.join(f'        case .{L}: return {L}' for L in LAYERS)
blocks = []
for L in LAYERS:
    body = '\n'.join('        ' + ln for ln in by[L])
    blocks.append(f'    static let {L}: String = """\n{body}\n        """' if by[L] else f'    static let {L}: String = """\n        """')

src = f'''import SwiftUI

// Generated by tools/forest-extension/scripts/emit_swift.py from the seeded scene in tools/forest-extension. Do not
// edit by hand; change the generator and regenerate.
// Live art data checksum at generation: {facts['data_sha256']}

/// Downward continuation of `ForestPathArt`: the same 937×1678 design space, with y = 0 on the live art's bottom edge,
/// the same layer IDs, data format, parser and CPU rasteriser.
nonisolated enum ForestPathExtensionArt {{
    typealias LayerID = ForestPathArt.LayerID
    typealias RGB = ForestPathArt.RGB

    static let size = ForestPathArt.size

    /// Mean colour of the scene's first ~200 u (ground at the seam): shown while the first raster is being made.
    static let seamGround = {rgb(ext_mean)}
    /// Colours beyond the scroll content: above the live art (top bounce) and below the extension (bottom bounce).
    static let topBounce = {rgb(live_top)}
    static let bottomBounce = {rgb(ext_bottom)}

    static func shapes(of id: LayerID) -> [ForestPathArt.Shape] {{
        parsed[id] ?? []
    }}

    /// All layers rasterised for a view of `size` points at `scale`, with the live art's aspect-fill transform. A pure
    /// function of its arguments, safe to call off the main thread.
    static func rasterize(size: CGSize, scale: CGFloat) -> CGImage? {{
        let all = LayerID.allCases.flatMap {{ shapes(of: $0) }}
        let width = Int((size.width * scale).rounded(.up)), height = Int((size.height * scale).rounded(.up))
        guard width > 0, height > 0 else {{ return nil }}
        let transform = fillTransform(for: size).concatenating(CGAffineTransform(scaleX: scale, y: scale))
        return ShapeRaster(width: width, height: height, shapes: all, transform: transform).image()
    }}

    /// Same rule as `ForestPathArt.fillTransform(for:)`: aspect-fill, centred.
    static func fillTransform(for viewSize: CGSize) -> CGAffineTransform {{
        let scale = max(viewSize.width / size.width, viewSize.height / size.height)
        return CGAffineTransform(
            translationX: (viewSize.width - size.width * scale) / 2,
            y: (viewSize.height - size.height * scale) / 2
        )
        .scaledBy(x: scale, y: scale)
    }}

    /// Shapes per layer, parsed once on first use.
    private static let parsed: [LayerID: [ForestPathArt.Shape]] = Dictionary(uniqueKeysWithValues: LayerID.allCases.map {{ id in
        var data = data(of: id)
        let shapes = data.withUTF8 {{ bytes in
            var reader = ShapeDataReader(bytes)
            var shapes: [ForestPathArt.Shape] = []
            while let shape = reader.nextShape() {{
                shapes.append(shape)
            }}
            return shapes
        }}
        return (id, shapes)
    }})

    static func data(of id: LayerID) -> String {{
        switch id {{
{cases}
        }}
    }}
}}

// MARK: - Layer data
//
// Back to front within each layer; format as in `ForestPathArt.data(of:)`.

nonisolated extension ForestPathExtensionArt {{
{chr(10).join(blocks)}
}}
'''
open(EXT_SWIFT, 'w').write(src)
print(EXT_SWIFT, '%.2f MB' % (len(src) / 1e6), len(ext), 'shapes', {L: len(v) for L, v in by.items() if v})
print('seamGround', rgb(ext_mean), 'top', rgb(live_top), 'bottom', rgb(ext_bottom))
